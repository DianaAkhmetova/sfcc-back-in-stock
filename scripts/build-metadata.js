#!/usr/bin/env node
/**
 * Builds the Business Manager "Site Import & Export" archives:
 *   backinstock_site_template.zip  <- metadata/site_template  (schema, service, job)
 *   backinstock_demo_data.zip      <- metadata/demo_data      (sample waitlist objects, demo only)
 *
 * Committed files keep placeholders; real values are injected from the git-ignored dw.json
 * (or env vars), so credentials / personal emails never land in the repository:
 *   webhook-url    / BIS_WEBHOOK_URL    -> service credential URL
 *   webhook-secret / BIS_WEBHOOK_SECRET -> service credential password (HMAC signing secret)
 *   demo-email     / BIS_DEMO_EMAIL     -> {{DEMO_EMAIL}} in demo data (falls back to "username")
 *
 * BM requires the archive's root folder to have the same name as the archive.
 */
const fs = require('fs')
const path = require('path')
const os = require('os')
const {execFileSync} = require('child_process')

const root = path.resolve(__dirname, '..')

let dw = {}
try {
    dw = JSON.parse(fs.readFileSync(path.join(root, 'dw.json'), 'utf8'))
} catch (e) {
    // optional
}
const webhookUrl = process.env.BIS_WEBHOOK_URL || dw['webhook-url']
const webhookSecret = process.env.BIS_WEBHOOK_SECRET || dw['webhook-secret']
const demoEmail = process.env.BIS_DEMO_EMAIL || dw['demo-email'] || dw.username

function fail(msg) {
    console.error(msg)
    process.exit(1)
}

const escapeXml = (s) =>
    s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

function buildArchive(srcName, archiveName, transform) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'bis-metadata-'))
    const staged = path.join(tmp, archiveName)
    fs.cpSync(path.join(root, 'metadata', srcName), staged, {recursive: true})
    transform(staged)
    const out = path.join(root, archiveName + '.zip')
    fs.rmSync(out, {force: true})
    execFileSync('zip', ['-qr', out, archiveName], {cwd: tmp})
    fs.rmSync(tmp, {recursive: true, force: true})
    console.log(`Built ${path.relative(root, out)}`)
}

if (!webhookUrl || !webhookSecret) {
    fail('Missing webhook-url / webhook-secret (dw.json) or BIS_WEBHOOK_URL / BIS_WEBHOOK_SECRET.')
}
if (!/^https:\/\//.test(webhookUrl)) fail('webhook-url must be https://')

buildArchive('site_template', 'backinstock_site_template', (dir) => {
    const file = path.join(dir, 'services.xml')
    const xml = fs
        .readFileSync(file, 'utf8')
        .replace(/<!--[\s\S]*?-->/, '<!-- Generated by scripts/build-metadata.js - contains credentials, do not commit. -->')
        .replace(/<url>[^<]*REPLACE_WITH_WEBHOOK_TOKEN[^<]*<\/url>/, () => `<url>${escapeXml(webhookUrl)}</url>`)
        .replace(/<password>REPLACE_WITH_RANDOM_HMAC_SECRET<\/password>/, () => `<password>${escapeXml(webhookSecret)}</password>`)
    if (xml.includes('REPLACE_WITH')) fail('Unreplaced placeholder left in services.xml')
    fs.writeFileSync(file, xml)
})

if (!demoEmail) fail('Missing demo-email / username in dw.json (or BIS_DEMO_EMAIL).')
buildArchive('demo_data', 'backinstock_demo_data', (dir) => {
    const file = path.join(dir, 'sites', 'RefArch', 'custom-objects', 'BackInStockProduct.xml')
    const xml = fs.readFileSync(file, 'utf8').split('{{DEMO_EMAIL}}').join(escapeXml(demoEmail.toLowerCase()))
    fs.writeFileSync(file, xml)
})
